def _parse(text: str, start_marker: str, end_marker: str) -> list[dict]:
    findings = []
    for block in re.findall(
        rf"{re.escape(start_marker)}(.*?){re.escape(end_marker)}", text, re.DOTALL
    ):
        def _field(key: str, b: str = block) -> str:
            m = re.search(rf"^{key}:\s*(.+)", b, re.MULTILINE)
            return m.group(1).strip() if m else ""

        snippet = re.search(r"SNIPPET:\s*```[^\n]*\n(.*?)```", block, re.DOTALL)
        fix     = re.search(r"FIX:\s*```[^\n]*\n(.*?)```",     block, re.DOTALL)
        attack  = re.search(r"ATTACK:\n(.*?)(?=\nFIX:|\Z)",     block, re.DOTALL)
        # ATTACK MODE(agents/recon_agent.py)のFINDINGマーカーはコードフェンス無しの
        # ATTACK_SCENARIO:/RECOMMENDED_ACTION:を使う（VULN/THREATのATTACK:/FIX:とは別形式）。
        attack_scenario = re.search(r"ATTACK_SCENARIO:\n(.*?)(?=\nRECOMMENDED_ACTION:|\Z)",
                                    block, re.DOTALL)
        recommended = re.search(r"RECOMMENDED_ACTION:\n(.*?)(?=\n---|\Z)", block, re.DOTALL)
        findings.append({
            "name":    _field("NAME") or _field("THREAT_TYPE") or _field("TITLE"),
            "severity": _field("SEVERITY"),
            "ref":     _field("CWE") or _field("MITRE_TTP") or _field("CATEGORY"),
            "lines":   _field("LINES") or _field("ATTACKER_IP") or _field("EVIDENCE"),
            "snippet": snippet.group(1).strip() if snippet else _field("TIMELINE"),
            "attack":  (attack.group(1).strip() if attack
                       else attack_scenario.group(1).strip() if attack_scenario else ""),
            "fix":     (fix.group(1).strip() if fix
                       else recommended.group(1).strip() if recommended else ""),
            "confidence": _field("CONFIDENCE"),
            # LLMが入力中のevidence_id(P1.2でsave_evidence有効時のみ提示)を引用した場合の
            # 生テキスト（カンマ/空白区切りを想定）。存在しないIDを採用しない検証は
            # 呼び出し側（agents/base_agent._findings_from_markers）の責務。
            "evidence_ids_raw": _field("EVIDENCE_IDS"),
        })
    return findings


def _render_finding(f: dict, lbl: dict) -> str:
    sev  = (f.get("severity") or "LOW").upper()
    name = html.escape(f.get("name") or "Unknown")
    bc   = f"b{sev}" if sev in ("CRITICAL", "HIGH", "MEDIUM", "LOW") else "bLOW"
    # 検証器アンサンブルで過半数一致に届かなかった所見（agents/base_agent.py _vote_findings）。
    # 除外はせず参考として本文に含めているため、ここでその旨を可視化する。
    minority = f.get("confidence") == "ENSEMBLE_MINORITY"
    name_html = f"{name} <span class=\"minority\">(単独検証)</span>" if minority else name
    meta_parts = [
        f"<b>{k}:</b> {html.escape(v)}"
        for k, v in [(lbl["ref"], f.get("ref", "")), (lbl["location"], f.get("lines", ""))]
        if v
    ]
    parts = []
    if "verification" in f:
        parts.append(f'<p>Verification: {html.escape(f["verification"])}</p>')
        refs = " ".join(f'<a href="{path}">{eid}</a>' for eid, path in f["evidence_refs"])
        parts.append(f'<p>Evidence: {refs or "not saved / unavailable"}</p>')
    if f.get("snippet"):
        parts.append(f'<div class="slabel">{lbl["vuln_code"]}</div><pre>{html.escape(f["snippet"])}</pre>')
    if f.get("attack"):
        parts.append(f'<div class="slabel">{lbl["attack"]}</div><pre>{html.escape(f["attack"])}</pre>')
    if f.get("fix"):
        parts.append(f'<div class="slabel">{lbl["fix"]}</div><pre>{html.escape(f["fix"])}</pre>')
    return (
        f'<div class="finding">'
        f'<div class="fhdr"><span class="badge {bc}">{html.escape(sev)}</span>'
        f'<span class="fname">{name_html}</span></div>'
        f'<div class="fbody">'
        f'<div class="fmeta">{" &nbsp;|&nbsp; ".join(meta_parts)}</div>'
        f'{"".join(parts)}</div></div>'
    )


def _findings_and_counts(mode: str, raw_text: str) -> tuple[list[dict], dict[str, int]]:
    """モードに応じて findings を抽出し、重大度カウントを返す（HTML/PDF/MD共用）。"""
    mode_u = mode.upper()
    if "DEFENSE" in mode_u:
        findings = _parse(raw_text, "---THREAT_START---", "---THREAT_END---")
    elif "ATTACK" in mode_u:
        # agents/recon_agent.py の SYSTEM_PROMPT は ---FINDING_START/END--- を使う
        # （VULN/THREATとはフィールド名も異なる。以前はここがVULNマーカーのまま
        # 検索しており、ATTACK MODEレポートの所見抽出が常に0件になっていた）。
        findings = _parse(raw_text, "---FINDING_START---", "---FINDING_END---")
    else:
        findings = _parse(raw_text, "---VULN_START---", "---VULN_END---")

    counts: dict[str, int] = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    for f in findings:
        sev = (f.get("severity") or "LOW").upper()
        if sev in counts:
            counts[sev] += 1
    return findings, counts


def _report_data(mode, target, raw_text, model, scan_result):
    """確定結果を優先し、旧マーカー入力は互換アダプターで読む。"""
    if scan_result is None:
        findings, counts = _findings_and_counts(mode, raw_text)
        return mode, target, "Evidence / coverage: unknown (legacy report)\n" + raw_text, model, findings, counts
    result = scan_result.to_dict() if hasattr(scan_result, "to_dict") else scan_result
    findings = []
    scan_id = result.get("scan_id", "")
    for item in result.get("findings", []):
        refs = []
        for eid in item.get("evidence_ids", []):
            if (re.fullmatch(r"scan_[a-f0-9]{12}", scan_id)
                    and re.fullmatch(r"evidence_[a-f0-9]{12}", eid)):
                refs.append((eid, f"evidence/{scan_id}/{eid}.json"))
        findings.append({
            "name": item.get("description", ""),
            "severity": item.get("severity", "LOW"),
            "ref": item.get("rule_id", ""), "lines": item.get("location", ""),
            "fix": item.get("remediation", ""),
            "snippet": item.get("snippet", ""), "attack": item.get("analysis", ""),
            "verification": item.get("verification_state", "observed"),
            "evidence_refs": refs,
            "confidence": ("ENSEMBLE_MINORITY" if
                           item.get("verifier_support", {}).get("ensemble_minority") else ""),
        })
    counts = {sev: sum(f["severity"].upper() == sev for f in findings)
              for sev in ("CRITICAL", "HIGH", "MEDIUM", "LOW")}
    summary = [f"State: {result.get('state', 'unknown')}",
               "Suppressed: 0 (suppression is not implemented)",
               "Evidence: excerpts may be masked or omitted; no references means not saved or unavailable."]
    summary.extend(f"Error: {e}" for e in result.get("errors", []))
    summary.extend(f"Coverage: {c.get('status')} | {c.get('target_ref')} | {c.get('reason', '')}"
                   for c in result.get("coverage", []))
    return (result.get("mode", mode), result.get("target", target), "\n".join(summary),
            result.get("model", model), findings, counts)


def _markdown_text(value):
    """入力由来のMarkdown構文とHTMLを無効にする。"""
    return re.sub(r"([\\`*_{}\[\]()#+.!|>~-])", r"\\\1", html.escape(str(value)))


def generate(
    mode: str,
    target: str,
    raw_text: str,
    model: str = "Unknown",
    timestamp: str | None = None,
    lang: str | None = None,
    scan_result=None,
) -> str:
    """スキャン結果をHTMLレポートとして生成して文字列で返す。"""
    if timestamp is None:
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lbl = _labels(lang)
    mode, target, raw_text, model, findings, counts = _report_data(
        mode, target, raw_text, model, scan_result)

    findings_section = ""
    if findings:
        rendered = "\n".join(_render_finding(f, lbl) for f in findings)
        findings_section = f'<h2>{lbl["findings"]} ({len(findings)})</h2>\n{rendered}'

    return _TEMPLATE.format(
        css=_CSS,
        html_lang=lbl["html_lang"],
        doc_title=lbl["doc_title"],
        report_h1=lbl["report_h1"],
        l_mode=lbl["scan_mode"], l_target=lbl["target"], l_engine=lbl["engine"],
        l_date=lbl["date"], l_genby=lbl["generated_by"], l_summary=lbl["summary"],
        l_raw=lbl["raw"], l_footer=lbl["footer"],
        title=html.escape(os.path.basename(target) if target else mode),
        mode=html.escape(mode),
        target=html.escape(target or "—"),
        model=html.escape(model),
        timestamp=html.escape(timestamp),
        version=html.escape(APP_VERSION),
        findings_section=findings_section,
        raw=html.escape(raw_text),
        # テンプレートは小文字プレースホルダ {critical} 等を使用するため変換する
        critical=counts["CRITICAL"],
        high=counts["HIGH"],
        medium=counts["MEDIUM"],
        low=counts["LOW"],
    )


def save_artifact(content: str, category: str, ext: str = "md",
                  reports_dir: str = "reports") -> str:
    """PoC・調査レポート等の生成物を reports/<category>/ に保存しパスを返す。

    category 例: "poc"（PoC） / "investigation"（調査レポート）。
    """
    out_dir = os.path.join(reports_dir, category)
    os.makedirs(out_dir, exist_ok=True)
    ts   = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = os.path.join(out_dir, f"{category}_{ts}.{ext}")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    return path


def save(html_content: str, mode: str, reports_dir: str = "reports") -> str:
    """レポートをファイルに保存してパスを返す。"""
    os.makedirs(reports_dir, exist_ok=True)
    ts   = datetime.now().strftime("%Y%m%d_%H%M%S")
    slug = re.sub(r"[^a-z0-9]", "_", mode.lower())[:20]
    path = os.path.join(reports_dir, f"report_{slug}_{ts}.html")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(html_content)
    return path


# ── PDF 出力 ────────────────────────────────────────────────
def generate_pdf(
    mode: str,
    target: str,
    raw_text: str,
    model: str = "Unknown",
    timestamp: str | None = None,
    lang: str | None = None,
    scan_result=None,
) -> bytes | None:
    """スキャン結果を日本語対応PDFとして生成しバイト列で返す。

    Pillow が利用できない環境では None を返す（呼び出し側でフォールバック）。
    """
    if timestamp is None:
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lbl = _labels(lang)
    mode, target, raw_text, model, findings, counts = _report_data(
        mode, target, raw_text, model, scan_result)
    from tools import pdf_writer
    return pdf_writer.render(
        meta={
            "mode": mode, "target": target or "—",
            "model": model, "timestamp": timestamp, "version": APP_VERSION,
        },
        counts=counts,
        findings=findings,
        raw_text=raw_text,
        labels=lbl,
    )


# ── Markdown 出力（バグバウンティ提出用） ─────────────────────
def generate_markdown(
    mode: str,
    target: str,
    raw_text: str,
    model: str = "Unknown",
    timestamp: str | None = None,
    lang: str | None = None,
    scan_result=None,
) -> str:
    """バグバウンティ提出用（HackerOne/Bugcrowd等）のMarkdownレポートを生成する。

    既存の ---VULN_START/END--- パーサをそのまま再利用し、Summary / Steps to
    Reproduce / Impact / Suggested Fix の4項目テンプレートで出力する
    （BOUNTY_ROADMAP.md Phase D）。
    """
    if timestamp is None:
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lbl = _labels(lang)
    mode, target, raw_text, model, findings, counts = _report_data(
        mode, target, raw_text, model, scan_result)
    if scan_result is not None:
        mode, target, model = map(_markdown_text, (mode, target, model))
        findings = [{k: (_markdown_text(v) if isinstance(v, str) and k not in ("snippet", "fix") else v)
                     for k, v in f.items()} for f in findings]

    lines = [
        f"# {lbl['doc_title']} — {mode}",
        "",
        f"- **{lbl['target']}**: {target or '—'}",
        f"- **{lbl['engine']}**: {model}",
        f"- **{lbl['date']}**: {timestamp}",
        f"- **{lbl['generated_by']}**: AI Security Audit System v{APP_VERSION}",
        "",
        f"## {lbl['summary']}",
        "",
        f"CRITICAL: {counts['CRITICAL']}  |  HIGH: {counts['HIGH']}  |  "
        f"MEDIUM: {counts['MEDIUM']}  |  LOW: {counts['LOW']}",
        "",
    ]
    if scan_result is not None:
        lines.extend([_markdown_text(raw_text), ""])
    else:
        lines.extend(["Evidence / coverage: unknown (legacy report)", ""])
    for f in findings:
        if "verification" in f:
            lines.extend([f"Verification: {f['verification']}", "Evidence: " + (
                " ".join(f"[{eid}]({path})" for eid, path in f["evidence_refs"])
                or "not saved / unavailable"), ""])
        sev = (f.get("severity") or "LOW").upper()
        name = f.get("name") or "Unknown"
        lines.append(f"## [{sev}] {name}")
        lines.append("")
        lines.append("### Summary")
        lines.append(name)
        lines.append("")
        if f.get("lines"):
            lines.append(f"**Location**: {f['lines']}")
            lines.append("")
        lines.append("### Steps to Reproduce")
        snippet = f.get("snippet") or "(詳細はレポート全文参照)"
        fence = "`" * max(3, max((len(m) + 1 for m in re.findall(r"`+", snippet)), default=3))
        lines.extend([fence, snippet, fence])
        lines.append("")
        lines.append("### Impact")
        lines.append(f.get("attack") or "(記載なし)")
        lines.append("")
        lines.append("### Suggested Fix")
        fix = f.get("fix") or "(記載なし)"
        fence = "`" * max(3, max((len(m) + 1 for m in re.findall(r"`+", fix)), default=3))
        lines.extend([fence, fix, fence])
        lines.append("")
    if not findings:
        lines.append("_（検出項目なし）_")
        lines.append("")
    lines.append("---")
    lines.append(lbl["footer"])
    return "\n".join(lines)


